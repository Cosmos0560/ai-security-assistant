BEGIN_MARKER: Final = (
    "<!-- aisa-comparison:begin (generated by "
    "`python -m ai_security_assistant.eval.compare_table --write README.md docs/live-eval`) -->"
)
END_MARKER: Final = "<!-- aisa-comparison:end -->"
MARKERS: Final = (BEGIN_MARKER, END_MARKER)
MOCK: Final = "mock"
MODELS: Final = (anthropic.DEFAULT_MODEL, ollama.DEFAULT_MODEL)
SETS: Final = ("main", "windows")
MISSING: Final = "n/a"

Document = dict[str, Any]


class ResultsError(ValueError):
    """A results file cannot be read."""


@dataclass(frozen=True)
class Column:
    name: str
    main: Document | None
    windows: Document | None

    def document(self, dataset: str) -> Document | None:
        return self.main if dataset == "main" else self.windows


# ---------------------------------------------------------------- the inputs


def mock_column() -> Column:
    run = run_eval(load_dataset())
    main = {**compute_metrics(run), **main_rates(run)}
    return Column(MOCK, main, compute_windows_metrics(run_eval(load_windows_dataset())))


def _read(path: Path) -> Document:
    try:
        document = json.loads(path.read_bytes())
    except (OSError, ValueError, RecursionError) as exc:
        raise ResultsError(f"{path.name}: cannot read it as JSON") from exc
    if not isinstance(document, dict):
        raise ResultsError(f"{path.name}: not a results document")
    return document


def _unused_because(document: Document, hashes: dict[str, str]) -> str | None:
    """Why this file cannot fill a cell, or None."""
    if document.get("complete") is not True:
        version = (document.get("prompt_versions") or {}).get("all", "unknown")
        return f"prompt version {version}; not marked complete"
    live = document.get("live") or {}
    if live.get("model") not in MODELS or live.get("dataset") not in SETS:
        return "not a model and set the table has"
    if document.get("dataset_sha256") != hashes[live["dataset"]]:
        return "run on another version of the dataset"
    return None


def load_results(folder: Path) -> tuple[dict[tuple[str, str], Document], list[tuple[str, str]]]:
    """``({(model, set): results}, [(file name, why it is not used)])``."""
    if not folder.is_dir():
        raise ResultsError(f"{folder.as_posix()} is not a directory")
    hashes = {"main": dataset_sha256(), "windows": dataset_sha256(windows_dataset_text())}
    found: dict[tuple[str, str], list[tuple[str, str, Document]]] = {}
    unused: list[tuple[str, str]] = []
    for path in sorted(folder.glob("*.json")):
        if path.name.endswith(".samples.json"):
            continue
        document = _read(path)
        why = _unused_because(document, hashes)
        if why is not None:
            unused.append((path.name, why))
            continue
        live = document["live"]
        key = (live["model"], live["dataset"])
        found.setdefault(key, []).append((str(live.get("date", "")), path.name, document))
    used: dict[tuple[str, str], Document] = {}
    for key, runs in found.items():
        runs.sort(key=lambda run: run[:2])
        used[key] = runs[-1][2]
        unused += [(name, "a later run replaces it") for _date, name, _document in runs[:-1]]
    return used, sorted(unused)


# ---------------------------------------------------------------- the cells


def _get(document: Document | None, *path: str) -> Any:
    node: Any = document
    for key in path:
        if not isinstance(node, dict) or key not in node:
            return None
        node = node[key]
    return node


def _cell(document: Document | None, *path: str) -> str:
    cell = _get(document, *path)
    if not isinstance(cell, dict) or not cell.get("of"):
        return MISSING
    return f"{cell['n']}/{cell['of']}"


def _latency(document: Document | None) -> str:
    latency = _get(document, "live", "latency_ms_all_calls")
    if not isinstance(latency, dict) or not latency.get("n"):
        return MISSING
    mean, p95 = latency["mean_ms"] / 1000, latency["p95_ms"] / 1000
    return f"{mean:.1f} s / {p95:.1f} s (n {latency['n']})"


def _versions(column: Column) -> str:
    seen = []
    for dataset in SETS:
        versions = _get(column.document(dataset), "prompt_versions")
        if versions:
            text = f"{versions.get('all', MISSING)} (`none`: {versions.get('none', MISSING)})"
            if text not in seen:
                seen.append(text)
    return ", ".join(seen) or MISSING


def _dates(column: Column) -> str:
    if column.name == MOCK:
        return "every gate run"
    dates = {_get(column.document(dataset), "live", "date") for dataset in SETS}
    return ", ".join(sorted(date for date in dates if date)) or MISSING


def _row(*cells: str) -> str:
    return "| " + " | ".join(cells) + " |"


def _header(*names: str) -> list[str]:
    return [_row(*names), _row(*("---" for _ in names))]


Value = Callable[[Column], str]


def _from(dataset: str, *path: str) -> Value:
    return lambda column: _cell(column.document(dataset), *path)


def _latency_of(dataset: str) -> Value:
    return lambda column: _latency(column.document(dataset))


