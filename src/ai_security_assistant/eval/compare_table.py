"""The model comparison block (D45): generated from committed results files, never edited by hand.

    python -m ai_security_assistant.eval.compare_table --check README.md docs/live-eval   # gate
    python -m ai_security_assistant.eval.compare_table --write README.md docs/live-eval

The block sits between ``BEGIN_MARKER`` and ``END_MARKER`` in README.md. Its inputs are the mock
eval, computed fresh, and the results files in the folder. A results file is used only if it says
``"complete": true`` and was run on the packaged dataset; of several runs of one model on one set,
the latest wins. Every file that is not used is named with the reason, and a missing measurement
is ``n/a``, never blank. Per-sample files (``*.samples.json``) are not inputs.
"""

