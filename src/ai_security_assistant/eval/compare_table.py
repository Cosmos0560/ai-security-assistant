def render_block(columns: Sequence[Column], unused: Sequence[tuple[str, str]]) -> str:
    """The Markdown between the markers (without them), ending in a newline."""
    out = _header("", *(f"`{column.name}`" for column in columns))
    out += [_row(label, *(value(column) for column in columns)) for label, value in SUMMARY_ROWS]
    out += [
        "",
        "Every cell is a count with its denominator. `mock` is the two deterministic mocks: in "
        "the first table the naive one gives attacks and rejections and the well-behaved one the "
        "review rows; its by-configuration table is the naive one throughout. The mocks' "
        "technique table is a placeholder, so their accuracy says nothing, and they measure no "
        "time.",
    ]
    for column in columns:
        if column.main is None and column.windows is None:
            out += [
                "",
                f"`{column.name}` is `{MISSING}`: no complete results file for it is committed.",
            ]
            continue
        out += [
            "",
            f"**`{column.name}` by configuration.**",
            "",
            *_header("measure", *(f"`{config}`" for config in CONFIGS)),
        ]
        for label, dataset, head, tail in CONFIG_ROWS:
            document = column.document(dataset)
            cells = (_cell(document, *head, config, *tail) for config in CONFIGS)
            out.append(_row(label, *cells))
    if unused:
        named = "; ".join(f"`{name}` ({why})" for name, why in unused)
        out += ["", f"Results files not used: {named}."]
    return "\n".join(out) + "\n"


def build_block(folder: Path) -> str:
    used, unused = load_results(folder)
    columns = [mock_column()]
    columns += [Column(m, used.get((m, "main")), used.get((m, "windows"))) for m in MODELS]
    return render_block(columns, unused)


# ---------------------------------------------------------------- the command


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m ai_security_assistant.eval.compare_table",
        description="Check or rewrite the generated comparison block in a README.",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", type=Path, metavar="README", help="fail if the block drifted")
    mode.add_argument("--write", type=Path, metavar="README", help="rewrite the block")
    parser.add_argument("results", type=Path, help="the folder of committed results files")
    args = parser.parse_args(argv)
    path: Path = args.check or args.write
    try:
        readme = path.read_bytes().decode("utf-8")
        block = build_block(args.results)
        if args.check is not None:
            if current_block(readme, MARKERS) != block:
                print("the comparison block differs from the results files; run --write")
                return 1
            print("the comparison block matches the results files")
            return 0
        path.write_bytes(replace_block(readme, block, MARKERS).encode("utf-8"))
    except (OSError, UnicodeDecodeError, MarkerError, ResultsError) as exc:
        print(f"compare_table: {type(exc).__name__}: {exc}")
        return 2
    print(f"rewrote the comparison block in {path.as_posix()}")
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through main() in the tests
    sys.exit(main())
