"""The README metrics block (D25): generated from the metrics document, never edited by hand.

The block sits between ``BEGIN_MARKER`` and ``END_MARKER`` in README.md. ``render_block`` is a
pure function of the metrics document, so the gate can regenerate it and compare it byte for byte
(after CRLF to LF normalization, D29) with what the README holds:

    python -m ai_security_assistant.eval.readme_table --check README.md   # the gate
    python -m ai_security_assistant.eval.readme_table --write README.md   # aisa eval --readme

Every cell shows its n (``46/48``) and a percentage with one decimal.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any, Final

from ai_security_assistant.eval.dataset import ATTACK_GOALS, CATEGORIES

BEGIN_MARKER: Final = "<!-- aisa-metrics:begin (generated by `aisa eval --readme README.md`) -->"
END_MARKER: Final = "<!-- aisa-metrics:end -->"
CONFIGS: Final = ("none", "detector-only", "validator-only", "all")


class MarkerError(ValueError):
    """The README does not hold exactly one well-formed metrics block."""


def cell(document: dict[str, int]) -> str:
    n, of = document["n"], document["of"]
    if of == 0:
        return f"{n}/{of} (n/a)"
    return f"{n}/{of} ({100 * n / of:.1f}%)"


def _row(*cells: str) -> str:
    return "| " + " | ".join(cells) + " |"


def _header(*names: str) -> list[str]:
    return [_row(*names), _row(*("---" for _ in names))]


def _ablation(totals: dict[str, Any]) -> list[str]:
    lines = _header("config", "attack success", "defended (of executed under none)", "schema-valid")
    for config in CONFIGS:
        defended = "n/a (baseline)" if config == "none" else cell(totals["defended"][config])
        lines.append(
            _row(
                f"`{config}`",
                cell(totals["attack_success"][config]),
                defended,
                cell(totals["schema_valid"][config]),
            )
        )
    return lines


def render_block(metrics: dict[str, Any]) -> str:
    """The Markdown between the markers (without them), ending in a newline."""
    full = metrics["totals"]["full"]
    held = metrics["totals"]["heldout"]
    data = metrics["dataset"]
    out: list[str] = [
        f"Dataset: {data['alerts']} synthetic alerts ({data['injection']} injection, "
        f"{data['benign']} benign, {data['hard_negative']} of them hard negatives); "
        f"{data['splits']['dev']} dev / {data['splits']['heldout']} held-out. Ablation provider: "
        f"`{metrics['providers']['ablation']}`, seed `{metrics['seed']}`.",
        "",
        "**Attack success by configuration (full set, naive mock).** The naive mock executed "
        f"{cell(full['executed_under_none'])} injections under `none`; the rest were not executed, "
        "which is not the same as defended.",
        "",
        *_ablation(full),
        "",
        "**Input detector (sanitize + wrap on).**",
        "",
        *_header("set", "injections flagged", "injections blocked", "benign flagged",
                 "benign blocked", "hard negatives flagged", "hard negatives blocked"),
    ]  # fmt: skip
    for name, totals in (("full", full), ("held-out", held)):
        det, fp, hard = (
            totals["detection"],
            totals["benign_false_positives"],
            totals["hard_negative_false_positives"],
        )
        out.append(
            _row(
                name,
                cell(det["flagged"]),
                cell(det["blocked"]),
                cell(fp["flagged"]),
                cell(fp["blocked"]),
                cell(hard["flagged"]),
                cell(hard["blocked"]),
            )
        )
    out += [
        "",
        f"**Held-out totals ({held['alerts']} alerts: {held['injections']} injection, "
        f"{held['benign']} benign).**",
        "",
        *_ablation(held),
        "",
        "**Per category (full set).** Detection from the `all` run; attack success per config.",
        "",
        *_header("category", "n", "flagged", "blocked", *(f"`{c}`" for c in CONFIGS)),
    ]
    for category in CATEGORIES:
        row = metrics["per_category"][category]
        out.append(
            _row(
                category,
                str(row["samples"]),
                cell(row["detection"]["flagged"]),
                cell(row["detection"]["blocked"]),
                *(cell(row["attack_success"][c]) for c in CONFIGS),
            )
        )
    out += [
        "",
        "**Per attack goal (full set).**",
        "",
        *_header("attack goal", "n", "executed under none", *(f"`{c}`" for c in CONFIGS)),
    ]
    for goal in ATTACK_GOALS:
        row = metrics["per_goal"][goal]
        out.append(
            _row(
                goal,
                str(row["samples"]),
                cell(row["executed_under_none"]),
                *(cell(row["attack_success"][c]) for c in CONFIGS),
            )
        )
    review = metrics["operational"]["benign_needs_human_review_all_well_behaved"]
    out += [
        "",
        "**Operational cost.** Benign alerts sent to human review under `all` with the "
        f"well-behaved mock: {cell(review)}.",
    ]
    return "\n".join(out) + "\n"


def _span(text: str) -> tuple[int, int]:
    if text.count(BEGIN_MARKER) != 1 or text.count(END_MARKER) != 1:
        raise MarkerError("README must hold each metrics marker exactly once")
    start = text.index(BEGIN_MARKER) + len(BEGIN_MARKER)
    end = text.index(END_MARKER)
    if end < start or text[start : start + 1] != "\n":
        raise MarkerError("the metrics markers are out of order or not on their own lines")
    return start + 1, end


def current_block(readme: str) -> str:
    start, end = _span(readme.replace("\r\n", "\n"))
    return readme.replace("\r\n", "\n")[start:end]


def replace_block(readme: str, block: str) -> str:
    text = readme.replace("\r\n", "\n")
    start, end = _span(text)
    return text[:start] + block + text[end:]


def readme_drift(readme: str, metrics: dict[str, Any]) -> bool:
    """True when the README block differs from the one ``metrics`` generates (LF-normalized)."""
    return current_block(readme) != render_block(metrics)


def _fresh_metrics() -> dict[str, Any]:
    from ai_security_assistant.eval.dataset import load_dataset
    from ai_security_assistant.eval.metrics import compute_metrics
    from ai_security_assistant.eval.runner import run_eval

    return compute_metrics(run_eval(load_dataset()))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m ai_security_assistant.eval.readme_table",
        description="Check or rewrite the generated metrics block in a README.",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", type=Path, metavar="README", help="fail if the block drifted")
    mode.add_argument("--write", type=Path, metavar="README", help="rewrite the block")
    args = parser.parse_args(argv)
    path: Path = args.check or args.write
    try:
        readme = path.read_bytes().decode("utf-8")
        metrics = _fresh_metrics()
        if args.check is not None:
            if readme_drift(readme, metrics):
                print("README metrics block differs from the eval output; run aisa eval --readme")
                return 1
            print("README metrics block matches the eval output")
            return 0
        path.write_bytes(replace_block(readme, render_block(metrics)).encode("utf-8"))
    except (OSError, UnicodeDecodeError, MarkerError) as exc:
        print(f"readme_table: {type(exc).__name__}: {exc}")
        return 2
    print(f"rewrote the metrics block in {path.as_posix()}")
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through main() in the tests
    sys.exit(main())
